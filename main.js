function projectRight(p, k) {
  const num = pad(pageOf(k) + 1), label = p.section;
  const play = (p.poster || p.still)
    ? `<button class="play" data-play="${p.id}">${p.video ? "▶︎ Play film" : "Film coming soon"}</button>` : "";
  const desc = `${p.title}, ${p.kind.toLowerCase()} by Amy Grindau`;
  if (p.poster) return pg("r", `${bg(p.poster, "bg--poster", "", `Poster for ${desc}`)}${play}`, { num, label, cls: "pg--black pg--film" });
  if (p.still) return pg("r", `${bg(p.still, "bg--screen", "", `Film still from ${desc}`)}${play}`, { num, label, cls: "pg--black pg--film", style: p.pageBg ? `background:${p.pageBg}` : "" });
  if (p.key.collage) {
    return pg("r", `<div class="collage">${p.key.collage.map((src, n) => `<img class="collage__item c${n}" src="${src}" alt="${p.title}, ${p.kind.toLowerCase()}, work ${n + 1}">`).join("")}</div>`,
      { num, label, cls: "pg--pink" });
  }
  const { src, fit = "cover", zoom, pos, bg: color = "white", blend } = p.key;
  const style = (zoom ? `background-size:${zoom * 100}% auto;background-position:${pos || "center"};` : "")
    + (blend ? `mix-blend-mode:${blend};` : "");
  return pg("r", bg(src, `bg--${fit}`, style, desc), { num, label, cls: `pg--${color}` });
}

