#!/usr/bin/env python3
"""
Images in two sizes: run after adding images to assets/web.

    python3 tools/make_sizes.py

For every JPG wider than 1000 px it creates a copy 800 px wide next to it (name@800.jpg)
and writes assets/web/sizes.js, so the website can load the small file on phones.
"""
import os, re, subprocess, json

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WEB = os.path.join(ROOT, "assets", "web")
SMALL = 800

def width(path):
    out = subprocess.run(["sips", "-g", "pixelWidth", path], capture_output=True, text=True).stdout
    return int(re.search(r"pixelWidth: (\d+)", out).group(1))

sizes, made = {}, 0
for d, _, files in os.walk(WEB):
    for f in sorted(files):
        if not f.lower().endswith(".jpg") or "@800" in f:
            continue
        src = os.path.join(d, f)
        w = width(src)
        if w <= 1000:
            continue
        small = src[:-4] + f"@{SMALL}.jpg"
        if not os.path.exists(small) or os.path.getmtime(small) < os.path.getmtime(src):
            subprocess.run(["sips", "--resampleWidth", str(SMALL), "-s", "formatOptions", "82", src, "--out", small], capture_output=True)
            made += 1
        sizes[os.path.relpath(src, ROOT)] = w

with open(os.path.join(WEB, "sizes.js"), "w") as fh:
    fh.write("// generated by tools/make_sizes.py: images that also exist 800 px wide (name@800.jpg), with their full width\n")
    fh.write("window.SIZES = " + json.dumps(sizes, indent=0, sort_keys=True) + ";\n")
print(f"ok: {len(sizes)} images with a small version ({made} new)")
