// Preload the images of the pages → no flicker when a page lands.
// First the spreads around the open one, the rest later when the browser is idle
// (so the first page appears fast, also on a phone).
const preloaded = new Set();
const preloadSpread = (sp) => sp && `${sp.left || ""}${sp.right || ""}`.replace(/url\('([^']+)'\)|src="([^"]+)"/g, (_, a, b) => {
  const src = a || b;
  if (preloaded.has(src)) return;
  preloaded.add(src);
  const im = new Image();
  im.src = src;
  im.decode?.().catch(() => {});
});
const idle = window.requestIdleCallback || ((f) => setTimeout(f, 300));
addEventListener("load", () => {
  let n = 0;
  const next = () => { if (n < spreads.length) { preloadSpread(spreads[n++]); idle(next); } };
  setTimeout(() => idle(next), 1500);
});

